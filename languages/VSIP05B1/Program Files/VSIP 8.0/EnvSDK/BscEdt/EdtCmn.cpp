/////////////////////////////////////////////////////////////////////////////
//
// Function:    FilesChanged (IVsFileChangeEvents interface)
//                Basically we check for read-only attribute changes
//                (for which we update the display immediately) and
//                file content changes for which we prompt the user
//                later to ask if the file should be reloaded.
//
// Parameters:
//    cChanges    Number of files changed.
//    rglpstrFile    Array of file names.
//    rggrfChange    Array of flags indicating type of changes.
//
// Returns:        An HRESULT
////////////////////////////////////////////////////////////////////////////
STDMETHODIMP CBscEditorDocument::FilesChanged(
                                    DWORD cChanges, 
                                    LPCOLESTR rglpstrFile[], 
                                    VSFILECHANGEFLAGS rggrfChange[])
{
    USES_CONVERSION; 

    ATLTRACE(TEXT("CBscEditorDocument::FilesChanged\n"));
    if (m_fZombie)
        return E_UNEXPECTED;        // recursion guard

    if ( (cChanges == 0) || (rglpstrFile == NULL) || (rggrfChange == NULL) )
        return E_INVALIDARG;

    if (m_cIgnoreFileChangeLevel != 0)
        return S_OK;    // we are currently in mode to ignore file changes

    for (DWORD i = 0; i < cChanges; i++)
    {
        if (rglpstrFile[i] && (_wcsicmp(rglpstrFile[i], m_bsFileName) == 0) )
        {
            // if the readonly state (file attributes) have changed we can immediately update
            // the editor to match the new state (either readonly or not readonly) immediately
            // without prompting the user.
            if (rggrfChange[i] & VSFILECHG_Attr)
            {
                DWORD dwAttr = GetFileAttributes(OLE2T(m_bsFileName));
                BOOL fIsSysReadOnly = (dwAttr != 0xFFFFFFFF) && (dwAttr & FILE_ATTRIBUTE_READONLY);
                SetReadOnly(fIsSysReadOnly, fIsSysReadOnly);
            }

            // if it looks like the file contents have changed (either the size or the modified
            // time has changed) then we need to prompt the user to see if we should reload the
            // file. it is important to not syncronisly reload the file inside of this FilesChanged
            // notification. first it is possible that there will be more than one FilesChanged 
            // notification being sent (sometimes you get separate notifications for file attribute
            // changing and file size/time changing). also it is the preferred UI style to not
            // prompt the user until the user re-activates the environment application window.
            // this is why we use a timer to delay prompting the user.
            if (rggrfChange[i] & (VSFILECHG_Time | VSFILECHG_Size))
            {
                if (!m_fFileChangedTimerSet)
                {
                    m_fFileChangedTimerSet = TRUE;

                    // In the in-place activation case we send the message to the
                    // RTF window but in the IVsWindowPane case we send the message
                    // to the parent window.
                    #ifdef INPLACE
                        ::SetTimer(m_hwndRTF, WFILECHANGEDTIMERID, 500, NULL);
                    #else
                        ::SetTimer(m_hwnd, WFILECHANGEDTIMERID, 500, NULL);
                    #endif //INPLACE
                }
            } 
        }
    }

    return S_OK;
}

