//                Determines if the selection is empty by checking if the first
//                character in the range is the same as the last. Note that if
//                the method detects an error it returns TRUE as if the
//                selection were empty.
// Parameters
//    None.
//
// Returns TRUE if selection is empty or there is an error, FALSE otherwise.
