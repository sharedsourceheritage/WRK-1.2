////////////////////////////////////////////////////////////////////////////////
//
// Function:    IsSupported (IVsToolBoxUser interface)
//                This method is called for items in the toolbox. Here we test
//                if we can paste them into the window and if so we return S_OK,
//                if not we return S_FALSE.
//
// Parameters:
//    pDO            Toolbox data object.
//
// Returns an HRESULT
////////////////////////////////////////////////////////////////////////////////
STDMETHODIMP CBscEditorDocument::IsSupported(IDataObject* pDO)
{
    _ASSERTE(pDO != NULL);
    if (!pDO)
        return E_POINTER;
    // Closedown check
    if (m_fZombie)
        return S_FALSE;

    // First we obtain the current selection from our document object.
    HRESULT                    hr;
    CComPtr<ITextSelection>    srpTextSelection;    // Current selection
    if (FAILED(hr = m_srpTextDocObj->GetSelection(&srpTextSelection)))
        return hr;

    // Here we merely get the IUnknown interface from the data object,
    // place it in a variant parameter and call the RTF control to
    // enquire whether or not we can paste the object.
    CComVariant vt;
    VariantInit(&vt);
    vt.vt = VT_UNKNOWN;
    if (FAILED(hr = pDO->QueryInterface(IID_IUnknown, (LPVOID *)&vt.punkVal)))
        return hr;

    long    fCanPaste;            // Paste flag.
    if (FAILED(hr = srpTextSelection->CanPaste(&vt, 0, &fCanPaste)))
        return hr;

    // If we can paste then we return S_OK
    if (fCanPaste == tomTrue)
        return S_OK;
    else
        return S_FALSE;
}

