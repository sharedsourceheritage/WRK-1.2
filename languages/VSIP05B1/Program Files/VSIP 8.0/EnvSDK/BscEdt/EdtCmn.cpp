/*****************************************************************************
** IVsDocDataFileChangeControl Implementation
*****************************************************************************/

// NOTE: all good editors will implement IVsPersistDocData::ReloadDocData. This 
// means that the editor also advises for file change events via
// SVsFileChangeEx service to listen if the file changes outside of the environment
// and then prompt to reload (see IVsFileChangeEvents::FilesChanged implementation).
// All editors that properly implement this reload feature need to implement
// IVsDocDataFileChangeControl interface to allow parties like SCC to tell the
// editor to ignore file changes at times (e.g. when SCC is getting the latest
// version of the file. SCC will directly call IVsPersistDocData::ReloadDocData
// at the right time. it does not want the user to be prompted to reload the file.

/////////////////////////////////////////////////////////////////////////////
//
// Function:    IgnoreFileChanges (IVsDocDataFileChangeControl interface)
//                Determines whether changes to doc data in files should be ignored.
//
// Parameters:
//    fIgnore        If TRUE changes should be ignored.
//
// Returns:        An HRESULT
////////////////////////////////////////////////////////////////////////////
STDMETHODIMP CBscEditorDocument::IgnoreFileChanges(
                    /* [in] */ BOOL fIgnore)

{
    ATLTRACE(TEXT("CBscEditorDocument::IgnoreFileChanges\n"));
    if (m_fZombie)
        return E_UNEXPECTED;        // recursion guard

    if (fIgnore)
    {
        m_cIgnoreFileChangeLevel++;
    }
    else 
    {
        _ASSERTE(m_cIgnoreFileChangeLevel > 0);
        if (m_cIgnoreFileChangeLevel > 0)
            m_cIgnoreFileChangeLevel--;

        // We need to check here if our file has changed from "Read Only"
        // to "Read/Write" or vice versa while the ignore level was non-zero.
        // This may happen when a file is checked in or out under source
        // code control. We need to check here so we can update our caption.
        BOOL fReadOnly = FStateGet(eFileStateFileSysReadOnly);  // Our recorded state
        DWORD dwAttr = GetFileAttributes(OLE2T(m_bsFileName));
        // Now determine the actual file Read Only or Read/Write state
        BOOL fIsSysReadOnly = (dwAttr != 0xFFFFFFFF) && (dwAttr & FILE_ATTRIBUTE_READONLY);

        // If the state has changed then we must update our caption etc.
        if ((fReadOnly && !fIsSysReadOnly) || (!fReadOnly && fIsSysReadOnly))
        {
            SetReadOnly(fIsSysReadOnly, fIsSysReadOnly);
        }
    }
    return S_OK;
}



