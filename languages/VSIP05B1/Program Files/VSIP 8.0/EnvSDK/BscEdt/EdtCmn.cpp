/////////////////////////////////////////////////////////////////////////////
//
// Function:    Load (IPersistFileFormat interface)
//                Loads the data from a given file.
//
// Parameters:
//    pszFilename    Full path name of file to load.
//    grfMode        Not used.
//    fReadOnly    If TRUE file is read-only.
//
// Returns:        An HRESULT
////////////////////////////////////////////////////////////////////////////
STDMETHODIMP CBscEditorDocument::Load( 
                    /* [in] */ LPCOLESTR pszFilename,
                    /* [in] */ DWORD grfMode,
                    /* [in] */ BOOL fReadOnly)
{
    ATLTRACE(TEXT("CBscEditorDocument::Load\n"));
    if (m_fZombie)
        return E_UNEXPECTED;        // recursion guard

    // according to IPersistFileFormat docs, this must be an existing filename
    if (pszFilename == NULL)
        return E_INVALIDARG;

    // Set the wait cursor while we are loading the file
    HRESULT hr;
    CComPtr<IVsUIShell> srpUIShell;

    // First we must get the UI service from the package object
    if (FAILED(hr = m_pCVsPkg->GetShellUISvc((IVsUIShell **) &srpUIShell)))
        return hr;
    if (FAILED(hr = srpUIShell->SetWaitCursor()))
        return hr;

    ResetState();                    // reset state flags

    BOOL fFileSysReadOnly;
    if (FAILED(hr = ReadFromFile(pszFilename, FALSE, &fFileSysReadOnly)))
        return hr;

    // Set appropriate flags
    SetNew(FALSE);
    SetDirty(FALSE);
    SetReadOnly(fReadOnly, fFileSysReadOnly);

    // If we have cached a file name previously because we were not able to
    // load at that time then we must load from the cached file name.
    if (!m_bsFileName || wcscmp(m_bsFileName, pszFilename) != 0)  // The compare will be true when load is called as part of reload
    {
        // Cache filename
        SetFileName(pszFilename);

        // Hook up to file change notifications
        if (m_vscookieFileChangeConnection != VSCOOKIE_NIL)
            SetFileChangeAdvise(NULL, FALSE);//unadvise
        SetFileChangeAdvise(pszFilename, TRUE);
        // Fire the LoadFile event
        FileLoadAdvise( m_fFileReloaded );
    }
    return S_OK;
}


/////////////////////////////////////////////////////////////////////////////
//
// Function:    Save (IPersistFileFormat interface)
//                Saves a copy of the object into the specified file.
//
// Parameters:
//    pszFilename        Filname string. If pszFileName is NULL, the object should
//                    save its data to the current file. 
//    fRemember        Indicates whether the pszFileName parameter is to be used
//                    as the current working file. If TRUE, pszFileName becomes
//                    the current file and the object should clear its dirty
//                    flag after the save. If FALSE, this save operation is a
//                    "Save A Copy As ..." operation. In this case, the current
//                    file is unchanged and the object should not clear its dirty
//                    flag. If pszFileName is NULL, the implementation should
//                    ignore the fRemember flag. 
//
//    nFormatIndex    Indicates the file format. If it indicates neither default
//                    nor RTF we return an error.
//
// Returns:            An HRESULT
////////////////////////////////////////////////////////////////////////////
STDMETHODIMP CBscEditorDocument::Save( 
                    /* [in] */ LPCOLESTR pszFilename,
                    /* [in] */ BOOL fRemember,
                    /* [in] */ DWORD nFormatIndex)
{
    HRESULT hr;

    ATLTRACE(TEXT("CBscEditorDocument::Save\n"));
    if (m_fZombie)
        return E_UNEXPECTED;        // recursion guard

    // pszFilename is NULL or same as m_bsFileName => Save, 
    // otherwise fRemember => SaveAs and !fRemember => SaveCopyAs

    // validate params
    if (NULL == pszFilename && !m_bsFileName)
        return E_UNEXPECTED;

    if (nFormatIndex != DEF_FORMAT_INDEX &&
        nFormatIndex != RTF_FORMAT_INDEX)
        return E_INVALIDARG;

    LPCWSTR pszSaveFileName = NULL;
    BOOL fDoingSave = FALSE;
    if ((NULL == pszFilename) ||
        (m_bsFileName.m_str &&     (0 == _wcsicmp(m_bsFileName, pszFilename))))
    {
        // Save
        _ASSERTE
        (
            FStateGet(eFileStateAllowEdits)
            ||
            (!FStateGet(eFileStateFileSysReadOnly) && !FStateGet(eFileStateUserReadOnly))
        );
        pszSaveFileName = m_bsFileName.m_str;
        fRemember = TRUE;
        fDoingSave = TRUE;
    }
    else
    {
        // Ensure that the filename is valid
        hr = CheckFileName(pszFilename);
        if (FAILED(hr)) 
            return hr;

        // SaveAs or SaveCopyAs
        pszSaveFileName = pszFilename;
    }

    // Suspend file change notifications on a save (doesn't matter for a SaveAs or SaveCopyAs as
    // we re not interested in notifications for those)
    if (fDoingSave)
        SuspendFileChangeAdvise(pszSaveFileName, TRUE);

    // do the actual save
    hr = WriteToFile(pszSaveFileName);

    // Resume file change notifications
    if (fDoingSave)
        SuspendFileChangeAdvise(pszSaveFileName, FALSE);


    if (FAILED(hr))
        return hr;    // save failed

    if (fRemember)
    {
        // Save or SaveAs  
        if (!fDoingSave)
        {
            // SaveAs - change our cached file name and switch over to listening file change
            // notifications on the new name
            _ASSERTE(pszSaveFileName != m_bsFileName.m_str);            
            SetFileChangeAdvise(m_bsFileName, FALSE);
            SetFileChangeAdvise(pszSaveFileName, TRUE);
            SetFileName(pszSaveFileName);
        }

        SetDirty(FALSE);
        SetReadOnly(FALSE, FALSE);
        SetNew(FALSE);
    }

    // Since all changes are now saved properly to disk, there's no need for a backup.
    m_bBackupObsolete = FALSE;
    return S_OK;
}


