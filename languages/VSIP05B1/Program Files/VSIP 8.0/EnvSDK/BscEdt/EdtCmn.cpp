// Function:    GetParaFormatState (Command handler helper)
//                Retrieve the paragraph format state based
//                on the lState parameter. We set the state DOWN if
//                lState corresponds to the current state and UP otherwise. 
//                If the file is read only we disable the command
//                to change the state.
//
// Parameters
//    lState        State can be alignment or numbering (bullet)
//
// Returns        The requested state.
//
////////////////////////////////////////////////////////////////////////////
DWORD CBscEditorDocument::GetParaFormatState(long lState)
{
    HRESULT                    hr;
    CComPtr<ITextSelection>    srpTextSelection;    // Current selection
    CComPtr<ITextPara>        srpTextPara;        // Paragraph object
    DWORD                    dwState;            // Return state
    long                    lCurrent;            // Current state

    // Get the current selection.
    if (FAILED(hr = m_srpTextDocObj->GetSelection(&srpTextSelection)))
        return OLECMDSTATE_DISABLED;

    // Get the current paragraph object for the selection.
    if (FAILED(hr = srpTextSelection->GetPara(&srpTextPara)))
        return OLECMDSTATE_DISABLED;

    // Get the alignment.
    if (FAILED(hr = srpTextPara->GetAlignment(&lCurrent)))
        return OLECMDSTATE_DISABLED;

    // If the current state is equal to lState then set the
    // command state DOWN otherwise UP.
    dwState = (lState == lCurrent ? OLECMDSTATE_DOWN : OLECMDSTATE_UP);

    // Disable the toggle command if the file is read only and not editable
    if (FIsReadOnly() && !FStateGet(eFileStateAllowEdits))
        dwState &= ~OLECMDF_ENABLED;

    return dwState;
}




