/////////////////////////////////////////////////////////////////////////////
//
// Function:    EnsureFileChange 
//                In this function we obtain the IVsFileChangeEx service
// Parameters:
//    None
// Returns:        An HRESULT
////////////////////////////////////////////////////////////////////////////
HRESULT CBscEditorDocument::EnsureFileChange()
{
    ATLTRACE(TEXT("CBscEditorDocument::EnsureFileChange\n"));

    if (m_srpVsFileChangeEx != NULL)
        return S_OK;

    HRESULT hr = S_OK;
    hr = m_pCVsPkg->GetShellSvc(SID_SVsFileChangeEx, IID_IVsFileChangeEx, (void **) &m_srpVsFileChangeEx);
    if (FAILED(hr))
        return hr;
    _ASSERTE(m_srpVsFileChangeEx != NULL);
    if (! m_srpVsFileChangeEx)
        return E_UNEXPECTED;

    return hr;
}


/////////////////////////////////////////////////////////////////////////////
//
// Function:    SetFileChangeAdvise 
//                In this function we inform the shell when we wish to receive 
//              events when our file is changed or we inform the shell when 
//              we wish not to receive events anymore.             
//
// Parameters:
//    pszFileName    File name string.
//    fStart        TRUE indicates advise, FALSE indicates unadvise.
//
// Returns:        An HRESULT
////////////////////////////////////////////////////////////////////////////
HRESULT CBscEditorDocument::SetFileChangeAdvise(
                                LPCWSTR pszFileName, 
                                BOOL fStart)
{
    ATLTRACE(TEXT("CBscEditorDocument::SetFileChangeAdvise\n"));

    HRESULT hr = EnsureFileChange();
    if (FAILED(hr))
        return hr;

    // Advise if fStart is TRUE, Unadvise if fStart is FALSE.
    if (fStart)
    {
        _ASSERTE(m_vscookieFileChangeConnection == VSCOOKIE_NIL);
        if (m_vscookieFileChangeConnection == VSCOOKIE_NIL)
        {
            hr = m_srpVsFileChangeEx->AdviseFileChange(
                /* [in] LPCOLESTR pszMkDocument     */ pszFileName,
                /* [in] VSFILECHANGEFLAGS grfFilter */ VSFILECHG_Attr | VSFILECHG_Time | VSFILECHG_Size, 
                /* [in] IVsFileChangeEvents *pFCE   */ static_cast<IVsFileChangeEvents*>(this),
                /* [out] VSCOOKIE *pvsCookie        */ &m_vscookieFileChangeConnection);
            _ASSERTE(SUCCEEDED(hr) && (m_vscookieFileChangeConnection != VSCOOKIE_NIL) );
        }
    }
    else
    {
        if (m_vscookieFileChangeConnection != VSCOOKIE_NIL)
        {
            hr = m_srpVsFileChangeEx->UnadviseFileChange(
                /* [in] VSCOOKIE vsCookie */ m_vscookieFileChangeConnection);
            _ASSERTE(SUCCEEDED(hr));
            m_vscookieFileChangeConnection = VSCOOKIE_NIL;
        }
    }
    return hr;
}


/////////////////////////////////////////////////////////////////////////////
//
// Function:    SuspendFileChangeAdvise 
//                In this function we suspend receeive file change events for
//                a file or we reinstate a previously suspended file depending
//                on the value of the given fSuspend flag.
//
// Parameters:
//    pszFileName    File name string.
//    fSuspend    TRUE indicates the file is to be suspended, FALSE indicates 
//                the file is to be reinstated.
//
// Returns:        An HRESULT
////////////////////////////////////////////////////////////////////////////
HRESULT CBscEditorDocument::SuspendFileChangeAdvise(
                                LPCWSTR pszFileName, 
                                BOOL fSuspend)
{
    ATLTRACE(TEXT("CBscEditorDocument::SuspendFileChangeAdvise\n"));

    HRESULT hr = EnsureFileChange();
    if (FAILED(hr))
        return hr;

    if (!fSuspend)
    {
        // we are transitioning from suspended to non-suspended state - so force a
        // sync first to avoid asynchronous notifications of our own change
        if (FAILED(hr = m_srpVsFileChangeEx->SyncFile(pszFileName)))
            return hr;
    }

    return m_srpVsFileChangeEx->IgnoreFile(NULL, pszFileName, fSuspend);
}

/////////////////////////////////////////////////////////////////////////////
//
// Function:    FileLoadAdvise 
//                In this function we send a RDTA_DocDataReloaded event for the
//              load or reload of a file.
//
// Parameters:
//    fReload        TRUE indicates that the file is reloaded.
//
// Returns:        An HRESULT
////////////////////////////////////////////////////////////////////////////
HRESULT CBscEditorDocument::FileLoadAdvise(
    BOOL    fReload
)
{
    HRESULT hr = S_OK;

    // Check the file name: it is possible to have an empty name in case
    // of reload, but it is an error in case of file load; in both cases,
    // if the file name is empty we can't fire any notification, so exit.
    if ( 0 == ::SysStringLen(m_bsFileName) )
    {
        return (fReload) ? S_OK : E_FAIL;
    }

    // Check if the pointer to the Running Document Table is valid
    if (m_srpRDT == NULL)
    {
        // Query the shell for the RDT
        hr = m_srpSiteSP->QueryService(
            SID_SVsRunningDocumentTable, 
            IID_IVsRunningDocumentTable,
            reinterpret_cast<void **>(&m_srpRDT)
        );
        // Check for errors
        if ( FAILED(hr) )
        {
            return hr;
        }
    }

    // Lock the current document in the RDT
    VSDOCCOOKIE docCookie;
    hr = m_srpRDT->FindAndLockDocument(
            RDT_ReadLock,    // Kind of lock
            m_bsFileName,    // Document to lock
            NULL,            // Pointer to a hierarchy pointer
            NULL,            // Pointer to an item ID
            0,
            &docCookie        // Cookie of the locked document
        );
    if ( SUCCEEDED(hr) )
    {
        // Fire the notification event
        hr = m_srpRDT->NotifyDocumentChanged(docCookie, RDTA_DocDataReloaded);
        // Here we don't check for success because, even if the previous operation
        // fails, we have to unlock the document.
        m_srpRDT->UnlockDocument(RDT_ReadLock, docCookie);
    }

    return hr;
}




