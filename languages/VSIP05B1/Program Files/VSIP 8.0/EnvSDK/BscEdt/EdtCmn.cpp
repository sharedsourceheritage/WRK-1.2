////////////////////////////////////////////////////////////////////////////
STDMETHODIMP CBscEditorDocument::SaveDocData( 
                    /* [in] */ VSSAVEFLAGS dwSave,
                    /* [out] */ BSTR *pbstrMkDocumentNew,
                    /* [out] */ BOOL *pfSaveCanceled)       
{
    ATLTRACE(TEXT("CBscEditorDocument::SaveDocData\n"));
    _ASSERTE(pfSaveCanceled != NULL);
    if (!pfSaveCanceled)
        return E_POINTER;
    *pfSaveCanceled = FALSE;        // Initialise output parameter flag.

    HRESULT hr;
    CComPtr<IVsUIShell> srpUIShell;
    if (m_fZombie)
        return E_UNEXPECTED;        // recursion guard

    _ASSERTE(m_bsFileName.m_str);
    CComBSTR bsFileNameTemp(m_bsFileName);



    switch (dwSave)
    {
    case VSSAVE_Save:                // Save the current file
        {
            // Get the QueryEditQuerySave service
            if (!m_srpVsQueryEditQuerySave2)
            {
                if 
                (
                    FAILED
                    ( 
                        hr = m_srpSiteSP->QueryService
                        (
                            SID_SVsQueryEditQuerySave,
                            IID_IVsQueryEditQuerySave2,
                            (LPVOID *) &m_srpVsQueryEditQuerySave2
                        )
                    )
                )
                    return hr;
            }
            VSQuerySaveResult  result;
            if 
            (
                FAILED
                ( 
                    hr = m_srpVsQueryEditQuerySave2->QuerySaveFile
                    (
                        /* [in ] const LPCOLESTR */             m_bsFileName,  // filename
                        /* [in ] VSQEQSFlags */                 0,             // Input flags        
                        /* [in ] VSQEQS_FILE_ATTRIBUTE_DATA */  NULL,          // Input flags        
                        /* [out] VSQuerySaveResult * */         &result        // Result flag
                    )
                )
            )
                return hr;
            // Test result of QuerySaveFile and process accordingly
            if (result == QSR_NoSave_UserCanceled)
            {
                *pfSaveCanceled = TRUE;
                return NOERROR;
            }
            else if (result == QSR_NoSave_Continue)
            {
                return NOERROR;
            }
            else if (result == QSR_SaveOK)
            {
                // Normal file save with no user dialog
                if (SUCCEEDED(hr = m_pCVsPkg->GetShellUISvc((IVsUIShell **) &srpUIShell)))
                {
                    hr = srpUIShell->SaveDocDataToFile(dwSave, (IPersistFileFormat*)this, bsFileNameTemp, pbstrMkDocumentNew, pfSaveCanceled);
                }
            }
            else if (result == QSR_ForceSaveAs)
            {
                // Save the file using user dialog and the IPersistFileFormat interface provided by
                // ourselves (i.e. this object (document)).
                if (SUCCEEDED(hr = m_pCVsPkg->GetShellUISvc((IVsUIShell **) &srpUIShell)))
                {
                    hr = srpUIShell->SaveDocDataToFile(VSSAVE_SaveAs, (IPersistFileFormat*)this, bsFileNameTemp, pbstrMkDocumentNew, pfSaveCanceled);
                }
            }
            else
            {
                return E_UNEXPECTED;
            }

            return hr;

        }
    case VSSAVE_SaveAs:
    case VSSAVE_SaveCopyAs:
        if (FStateGet(eFileStateNew))
        {
            // Append the file extension
            m_bsFileName.Append(L".rtf");
        }
        // Save the file using user dialog and the IPersistFileFormat interface provided by
        // ourselves (i.e. this object (document)).
        if (SUCCEEDED(hr = m_pCVsPkg->GetShellUISvc((IVsUIShell **) &srpUIShell)))
        {
            hr = srpUIShell->SaveDocDataToFile(dwSave, (IPersistFileFormat*)this, bsFileNameTemp, pbstrMkDocumentNew, pfSaveCanceled);
        }

        return hr;

    default:
        return E_INVALIDARG;
    }

}


