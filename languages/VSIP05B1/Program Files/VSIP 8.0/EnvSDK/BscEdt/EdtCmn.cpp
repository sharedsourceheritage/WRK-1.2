/////////////////////////////////////////////////////////////////////////////
//
// Function:    QueryStatus (IOleCommandTarget interface)
//                Queries the object for the status of one or more commands
//                generated by user interface events. We handle the standard
//                command set and the set we have registered (see BscEdtid.h)
//
// Parameters:
//    pguidCmdGroup    Command group - the standard set or the one we've registered.
//    cCmds            Number of commands
//    prgCmds            Array of commands
//    pCmdText        We do not use this.
//
// Returns:        An HRESULT
////////////////////////////////////////////////////////////////////////////
STDMETHODIMP CBscEditorDocument::QueryStatus(const GUID *pguidCmdGroup, ULONG cCmds, OLECMD prgCmds[], OLECMDTEXT *pCmdText)
{
    ATLTRACE(TEXT("CBscEditorDocument::QueryStatus\n"));
    if (m_fZombie)
        return E_UNEXPECTED;        // guard

    _ASSERTE(cCmds==1);
    CComPtr<ITextSelection> srpTextSelection;    // Smart pointer to current selection
    long                    fCanPaste;            // Flag indicating whether paste is possible
    HRESULT                    hr;

    if (prgCmds==NULL)
        return E_INVALIDARG;
    
    if (pguidCmdGroup == NULL)
    {
        return OLECMDERR_E_NOTSUPPORTED;
    }
    else if (CMDSETID_StandardCommandSet97 == *pguidCmdGroup)
    {
        switch(prgCmds[0].cmdID)
        {
        default:
            return OLECMDERR_E_NOTSUPPORTED;

        case cmdidCopy:
            prgCmds[0].cmdf = (FEmptySelection() ? OLECMDSTATE_DISABLED : OLECMDSTATE_UP);
            break;

        case cmdidCut:
        case cmdidDelete:
            prgCmds[0].cmdf = (FEmptySelection() || (FIsReadOnly()&& !FStateGet(eFileStateAllowEdits))) ? OLECMDSTATE_DISABLED : OLECMDSTATE_UP;
            break;

        case cmdidPaste:
            // Note that if the file is "Read Only" and not edit enabled then cmdidPaste is disabled
            if (FIsReadOnly() && !FStateGet(eFileStateAllowEdits))
            {
                prgCmds[0].cmdf = OLECMDSTATE_DISABLED;
            }
            else
            {
                // Get the current selection and test whether we can paste from the clipboard.
                if (FAILED(hr = m_srpTextDocObj->GetSelection(&srpTextSelection)))
                    return hr;
                srpTextSelection->CanPaste(NULL, 0, &fCanPaste);
                prgCmds[0].cmdf = (m_hwndRTF && fCanPaste == tomTrue) ? OLECMDSTATE_UP : OLECMDSTATE_DISABLED;
            }
            break;

        case cmdidBold:
            prgCmds[0].cmdf = GetCharFormatState(CFE_BOLD);
            break;

        case cmdidItalic:
            prgCmds[0].cmdf = GetCharFormatState(CFE_ITALIC);
            break;

        case cmdidUnderline:
            prgCmds[0].cmdf = GetCharFormatState(CFE_UNDERLINE);
            break;

        case cmdidJustifyLeft:
            prgCmds[0].cmdf = GetParaFormatState(tomAlignLeft);
            break;

        case cmdidJustifyRight:
            prgCmds[0].cmdf = GetParaFormatState(tomAlignRight);
            break;

        case cmdidJustifyCenter:
            prgCmds[0].cmdf = GetParaFormatState(tomAlignCenter);
            break;

        case cmdidFontName:
            prgCmds[0].cmdf = OLECMDSTATE_UP;
            break;

        case cmdidFontSize:
            prgCmds[0].cmdf = OLECMDSTATE_UP;
            break;

        case cmdidPasteNextTBXCBItem:
            prgCmds[0].cmdf = OLECMDF_SUPPORTED;
            // Note that if the file is "Read Only" and not edit enabled then cmdidPasteNextTBXCBItem is disabled
            if (FIsReadOnly() && !FStateGet(eFileStateAllowEdits))
            {
                prgCmds[0].cmdf = OLECMDSTATE_DISABLED;
            }
            else
            {
                if (CanCycleClipboard())
                    prgCmds[0].cmdf |= OLECMDF_ENABLED;
            }
            break;
        }
    }
    else if (CMDSETID_StandardCommandSet2K == *pguidCmdGroup)
    {
        switch(prgCmds[0].cmdID)
        {
        default:
            return OLECMDERR_E_NOTSUPPORTED;

        case ECMD_BULLETEDLIST:
            prgCmds[0].cmdf = GetBulletState();
            break;
        
        case ECMD_INSERT:
            prgCmds[0].cmdf = (LGetSelFlags() & tomSelOvertype) ? OLECMDSTATE_DOWN : OLECMDSTATE_UP;
            break;
        }
    }
    else if (GUID_BscEditorCmdset == *pguidCmdGroup)
    {
        switch(prgCmds[0].cmdID)
        {
        default:
            return OLECMDERR_E_NOTSUPPORTED;

        case icmdStrike:
            prgCmds[0].cmdf = GetCharFormatState(CFE_STRIKEOUT);
            break;
        }

    }
    else
        return OLECMDERR_E_UNKNOWNGROUP;

    return NOERROR;
}


/////////////////////////////////////////////////////////////////////////////
//
// Function:    Exec (IOleCommandTarget interface)
//                Executes a specified command.
//
// Parameters:
//    pguidCmdGroup    Command group - the standard set or the one we've registered.
//    CmdID            Command ID within group
//    nCmdexecopt        We do not use this.
//    pvaIn            We do not use this.
//    pvaOut            We do not use this.
//
// Returns:        An HRESULT
////////////////////////////////////////////////////////////////////////////
STDMETHODIMP CBscEditorDocument::Exec(const GUID *pguidCmdGroup, DWORD nCmdID, DWORD nCmdexecopt, VARIANT *pvaIn, VARIANT *pvaOut)
{
    ATLTRACE(TEXT("CBscEditorDocument::Exec\n"));
    if (m_fZombie)
        return E_UNEXPECTED;        // recursion guard

    CComPtr<ITextSelection> srpTextSelection;
    HRESULT                    hr = S_OK;

    // The IOleCommandTarget::Exec handler should take care of reporting
    // error messages to the user that occur in the execution of a command.
    // The convention is that the function that calls ReportErrorInfo()
    // should clear any cached error message before calling the functions
    // that could possibly generate errors.
    _AtlModule.ClearErrorInfo();    

    if (pguidCmdGroup == NULL)
    {
        return OLECMDERR_E_NOTSUPPORTED;
    }
    else if (CMDSETID_StandardCommandSet97 == *pguidCmdGroup)
    {
        switch (nCmdID)
        {
        default:    
            return OLECMDERR_E_NOTSUPPORTED;

        case cmdidCut:
            _ASSERTE(m_hwndRTF);
            if (FAILED(hr = m_srpTextDocObj->GetSelection(&srpTextSelection)))
                return hr;
            hr = srpTextSelection->Cut(NULL);
            break;

        case cmdidCopy:
            _ASSERTE(m_hwndRTF);
            if (FAILED(hr = m_srpTextDocObj->GetSelection(&srpTextSelection)))
                return hr;
            hr = srpTextSelection->Copy(NULL);
            break;

        case cmdidPaste:
            _ASSERTE(m_hwndRTF);
            if (FAILED(hr = m_srpTextDocObj->GetSelection(&srpTextSelection)))
                return hr;
            hr = srpTextSelection->Paste(NULL, 0);
            break;

        case cmdidDelete:
            _ASSERTE(m_hwndRTF);
            if (FAILED(hr = m_srpTextDocObj->GetSelection(&srpTextSelection)))
                return hr;
            hr = srpTextSelection->Delete(tomCharacter, 0, NULL);
            break;

        case cmdidBold:
            SetCharFormatState(CFE_BOLD);
            break;

        case cmdidItalic:
            SetCharFormatState(CFE_ITALIC);
            break;

        case cmdidUnderline:
            SetCharFormatState(CFE_UNDERLINE);
            break;

        case cmdidJustifyLeft:
            SetParaFormatState(tomAlignLeft);
            break;

        case cmdidJustifyRight:
            SetParaFormatState(tomAlignRight);
            break;

        case cmdidJustifyCenter:
            SetParaFormatState(tomAlignCenter);
            break;

        case cmdidFontNameGetList:
            // This command fills the drop-down list for the font name combo box.
            if (OLECMDEXECOPT_DODEFAULT == nCmdexecopt)
            {
                hr = FillFontNameArray(pvaOut);
            }
            break;

        case cmdidFontName:
            if (OLECMDEXECOPT_DODEFAULT == nCmdexecopt)
            {
                // Is a string being passed in? If so we set the newly
                // selected font name.
                if (NULL != pvaIn)
                {
                    // We allow no modifications if the file is read only and not editable.
                    if (!FIsReadOnly() || FStateGet(eFileStateAllowEdits))
                        SetFontName(pvaIn); 
                    return S_OK;
                }
                else
                {
                    // Clear our in/out variant and then retrieve the 
                    // current font name.
                    _ASSERTE(pvaOut != NULL);
                    ::VariantClear(pvaOut);

                    GetFontName(pvaOut); 
                    return S_OK;
                }
            }
            break;

        case cmdidFontSizeGetList:
            // This command fills the drop-down list for the font size combo box.
            if (OLECMDEXECOPT_DODEFAULT == nCmdexecopt)
            {
                hr = FillFontSizeArray(pvaOut);
            }
            break;

        case cmdidFontSize:
            if (OLECMDEXECOPT_DODEFAULT == nCmdexecopt)
            {
                // Is a string being passed in? If so we set the newly
                // selected font point size.
                if (NULL != pvaIn)
                {
                    // We allow no modifications if the file is read only and not editable.
                    if (!FIsReadOnly() || FStateGet(eFileStateAllowEdits))
                        SetFontSize(pvaIn); 
                    return S_OK;
                }
                else
                {
                    // Clear our in/out variant and then retrieve the 
                    // current font point size.
                    _ASSERTE(pvaOut != NULL);
                    ::VariantClear(pvaOut);

                    GetFontSize(pvaOut); 
                    return S_OK;
                }
            }
            break;

        case cmdidPasteNextTBXCBItem:
            PasteClipboardObject();
            break;
        }

    }
    else if (CMDSETID_StandardCommandSet2K == *pguidCmdGroup)
    {
        switch (nCmdID)
        {
        default:    
            return OLECMDERR_E_NOTSUPPORTED;

        case ECMD_BULLETEDLIST:
            // We toggle the bullet state here
            SetBulletState();
            break;

        case ECMD_INSERT:
            {
            long grfFlags = LGetSelFlags();
            grfFlags = (grfFlags & tomSelOvertype) ? (grfFlags & ~tomSelOvertype) : (grfFlags | tomSelOvertype);
            SetSelFlags(grfFlags);
            StatusBar_UpdateInsMode();
            }
            break;
        }
    }
    else if (GUID_BscEditorCmdset == *pguidCmdGroup)
    {

        switch (nCmdID)
        {
        default:    
            return OLECMDERR_E_NOTSUPPORTED;

        case icmdStrike:
            SetCharFormatState(CFE_STRIKEOUT);
            break;
        }
    }
    else
        return OLECMDERR_E_UNKNOWNGROUP;

    // Display any error message to the user and then reset the returned "hr"
    // to NOERROR because the error has been handled.
    if (FAILED(hr))
    {
        _AtlModule.ReportErrorInfo(hr);
        hr = S_OK;
    }
    else
    {
        // Here we perform macro recording if it's switched on. Note that
        // although macro recording may fail we do not report any errors.
        EstablishRecordState();
        if (m_fMacroRecording)
        {
            RecordCommand(pguidCmdGroup, nCmdID);
        }
    }

    return hr;
}


