/////////////////////////////////////////////////////////////////////////////
//
// Function:    PasteClipboardObject
//                Calls a function on the IVsToolboxClipboardCycler interface
//                to obtain the data object to be pasted, inserts the object in
//                a variant and then calls the paste function in the RTF
//                control for current selection or insertion point.
//                Note that this method gets invoked as a result of the
//                execution of command cmdidPasteNextTBXCBItem (CTRL-SHIFT-V).
//
// Parameters:
//    None
//
// Returns:        an HRESULT.
////////////////////////////////////////////////////////////////////////////
HRESULT CBscEditorDocument::PasteClipboardObject(void)
{
    if (!m_srpVsToolboxClipboardCycler)
        return E_FAIL;

    // Get the data object to be pasted.
    CComPtr<IDataObject> srpDO;
    HRESULT hr = m_srpVsToolboxClipboardCycler->GetAndSelectNextDataObject(static_cast<IVsToolboxUser*>(this), &srpDO);

    if (S_OK != hr) // didn't succeed?
        return hr; // bail out

    // Now we obtain the current selection from our document object.
    CComPtr<ITextSelection>    srpTextSelection;    // Current selection
    if (FAILED(hr = m_srpTextDocObj->GetSelection(&srpTextSelection)))
        return hr;

    // We now need the current start character position of the start
    // of the current selection. After the paste the start position
    // will be moved to the end of inserted text. We then need to
    // move the start back to original position so that we can
    // highlight the inserted text such that we can cycle through
    // our clipboard items.
    long    cpOrigStart;
    if (FAILED(hr = srpTextSelection->GetStart(&cpOrigStart)))
        return hr;

    // Here we merely get the IUnknown interface from the data object,
    // place it in a variant parameter and call the RTF control to
    // paste the object. 
    CComVariant vt;
    VariantInit(&vt);
    vt.vt = VT_UNKNOWN;
    if (FAILED(hr = srpDO->QueryInterface(IID_IUnknown, (LPVOID *)&vt.punkVal)))
        return hr;

    if (FAILED(hr = srpTextSelection->Paste(&vt, 0)))
        return hr;

    // Move our start position back to the original insertion point.
    // In order to do this we need to get the current start position
    // and move the selection start backwards by the difference
    // between our new start position and the original.
    long    cpNewStart;
    if (FAILED(hr = srpTextSelection->GetStart(&cpNewStart)))
        return hr;
    if (FAILED(hr = srpTextSelection->MoveStart(tomCharacter, cpOrigStart - cpNewStart, NULL)))
        return hr;

    // Select the pasted text
    if (FAILED(hr = srpTextSelection->Select()))
        return hr;

    return S_OK;
}












