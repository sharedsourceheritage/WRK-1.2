//
// Function:    ItemPicked (IVsToolBoxUser interface)
//                This function obtains the current selection
//                and pastes the data object via the returned
//                interface. The function is called when the
//                user double clicks on a (supported) item in
//                the toolbox in order to paste it into the 
//                RTF window.
//
// Parameters:
//    pDO            Toolbox data object.
//
// Returns an HRESULT
////////////////////////////////////////////////////////////////////////////////
STDMETHODIMP CBscEditorDocument::ItemPicked(IDataObject* pDO)
{
    _ASSERTE(pDO != NULL);
    if (!pDO)
        return E_POINTER;
    // Closedown check
    if (m_fZombie)
        return S_FALSE;

    // First we obtain the current selection from our document object.
    HRESULT                    hr;
    CComPtr<ITextSelection>    srpTextSelection;    // Current selection
    if (FAILED(hr = m_srpTextDocObj->GetSelection(&srpTextSelection)))
        return hr;

    // Here we merely get the IUnknown interface from the data object,
    // place it in a variant parameter and call the RTF control to
    // paste the object. 
    CComVariant vt;
    VariantInit(&vt);
    vt.vt = VT_UNKNOWN;
    if (FAILED(hr = pDO->QueryInterface(IID_IUnknown, (LPVOID *)&vt.punkVal)))
        return hr;

    if (FAILED(hr = srpTextSelection->Paste(&vt, 0)))
        return hr;

    return S_OK;
}


