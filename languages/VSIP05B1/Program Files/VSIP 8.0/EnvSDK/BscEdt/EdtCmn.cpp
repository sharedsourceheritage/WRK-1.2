/////////////////////////////////////////////////////////////////////////////
//
// Function:    StatusBar_UpdatePos (Helper function for IVsStatusBarUser::SetInfo)
//                Sets the current selection (or insertion point).
//
// Parameters:
//    None
//
// Returns:        Nothing. Note that we ignore failures in this function.
////////////////////////////////////////////////////////////////////////////
void CBscEditorDocument::StatusBar_UpdatePos()
{
    if (m_srpVsStatusBar)
    {
        long                    cpMin, cpMax;        // Selection min and max.            
        HRESULT                    hr;
        CComPtr<ITextSelection>    srpTextSelection;    // Current selection

        // Get the current selection and its start and end character positions.
        if (FAILED(hr = m_srpTextDocObj->GetSelection(&srpTextSelection)))
            return;
        if (FAILED(hr = srpTextSelection->GetStart(&cpMin)))
            return;
        if (FAILED(hr = srpTextSelection->GetEnd(&cpMax)))
            return;

        // Figure out which end is active (has the insertion pt)
        long chrActiveEnd = (LGetSelFlags() & tomSelStartActive) ? cpMin : cpMax;

        // There is no straightforward way to get the character position within
        // the line via the interface so we send messages to the RTF window for 
        // this data.
        long iLine = (long)SendMessage(m_hwndRTF, EM_EXLINEFROMCHAR, 0, chrActiveEnd);
        long iChar = chrActiveEnd - (long)SendMessage(m_hwndRTF, EM_LINEINDEX, (WPARAM) -1, 0L);    // note col is really the char # from the beginning of the line (like Word does)

        // set using the IVsStatusBar interface
        CComVariant vtLine(iLine+1, VT_I4);
        CComVariant vtChar(iChar+1, VT_I4);    
        m_srpVsStatusBar->SetLineChar(&vtLine, &vtChar);
    }
}


/////////////////////////////////////////////////////////////////////////////
//
// Function:    StatusBar_UpdateInsMode (Helper function for IVsStatusBarUser::SetInfo)
